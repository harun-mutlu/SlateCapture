    static Dictionary<string, string>? _current;

    public static string Code { get; private set; } = "en";

    public static string LanguageName => Languages.FirstOrDefault(l => l.Code == Code).Name ?? Code;

    public static void Use(string code)
    {
        Code = code;
        _current = code == "tr" ? Turkish : English;
    }

    public static string T(string key) => (_current ?? English).TryGetValue(key, out var s) ? s : English.GetValueOrDefault(key, key);

    public static string T(string key, params object[] args) => string.Format(T(key), args);

